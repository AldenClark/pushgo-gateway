//! Ordinary Sender input. Rules mirror Gateway MessageIntent and value normalizers.
use crate::store::{KernelError, Result, now};
use serde::{Deserialize, Deserializer};
use serde_json::{Map, Value};
use std::collections::BTreeMap;

pub const MAX_TTL_MS: i64 = 30 * 86_400_000;
#[derive(Debug, Deserialize, Clone, Default)]
pub struct AcceptRequest {
    pub channel_id: String,
    pub password: String,
    pub title: String,
    #[serde(default)]
    pub body: Option<String>,
    #[serde(default, deserialize_with = "empty_none")]
    pub op_id: Option<String>,
    #[serde(default, deserialize_with = "timestamp")]
    pub ttl: Option<i64>,
    #[serde(default, deserialize_with = "timestamp")]
    pub occurred_at: Option<i64>,
    #[serde(default)]
    pub severity: Option<String>,
    #[serde(default)]
    pub url: Option<String>,
    #[serde(default)]
    pub images: Vec<String>,
    #[serde(default)]
    pub ciphertext: Option<String>,
    #[serde(default)]
    pub tags: Vec<String>,
    #[serde(default, deserialize_with = "metadata")]
    pub metadata: Map<String, Value>,
    #[serde(default)]
    pub thing_id: Option<String>,
    #[serde(default, rename = "message_id", deserialize_with = "forbidden")]
    pub(crate) message_id: Option<Value>,
}
fn invalid(message: &str) -> KernelError {
    KernelError::Invalid(message.into())
}
fn forbidden<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Option<Value>, D::Error> {
    let _ = serde::de::IgnoredAny::deserialize(d)?;
    Err(serde::de::Error::custom(
        "message_id is generated by the gateway",
    ))
}
fn empty_none<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Option<String>, D::Error> {
    Ok(Option::<String>::deserialize(d)?.and_then(|v| optional(Some(v))))
}
fn timestamp<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Option<i64>, D::Error> {
    let v = Option::<Value>::deserialize(d)?;
    let n = match v {
        None | Some(Value::Null) => return Ok(None),
        Some(Value::String(s)) if s.trim().is_empty() => return Ok(None),
        Some(Value::String(s)) => s.trim().parse::<i64>().map_err(serde::de::Error::custom)?,
        Some(Value::Number(n)) => n
            .as_i64()
            .ok_or_else(|| serde::de::Error::custom("timestamp must be integer"))?,
        _ => return Err(serde::de::Error::custom("timestamp must be integer")),
    };
    Ok(Some(if n.unsigned_abs() < 1_000_000_000_000 {
        n.saturating_mul(1000)
    } else {
        n
    }))
}
fn metadata<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Map<String, Value>, D::Error> {
    let v = Option::<Map<String, Value>>::deserialize(d)?.unwrap_or_default();
    let mut out = Map::new();
    for (k, v) in v {
        let k = k.trim();
        if k.is_empty() || out.insert(k.to_owned(), v).is_some() {
            return Err(serde::de::Error::custom("metadata key invalid"));
        }
    }
    Ok(out)
}
fn optional(v: Option<String>) -> Option<String> {
    v.and_then(|s| {
        let s = s.trim();
        (!s.is_empty()).then(|| s.to_owned())
    })
}
fn list(v: Vec<String>, max: usize) -> Result<Vec<String>> {
    if v.len() > 32 {
        return Err(invalid("list exceeds max length"));
    }
    let mut out = Vec::new();
    for s in v {
        let s = s.trim();
        if s.is_empty() || s.len() > max {
            return Err(invalid("invalid list item"));
        }
        if !out.iter().any(|v| v == s) {
            out.push(s.to_owned())
        }
    }
    Ok(out)
}
pub(crate) fn op_id(raw: &str) -> Result<String> {
    let s = raw.trim();
    if s.is_empty()
        || s.len() > 128
        || !s
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | ':' | '-'))
    {
        return Err(invalid("op_id invalid"));
    }
    Ok(s.into())
}
pub(crate) fn password(raw: &str) -> Result<&str> {
    let s = raw.trim();
    if !(8..=128).contains(&s.len()) {
        return Err(invalid("channel password length must be between 8 and 128"));
    }
    Ok(s)
}
pub(crate) struct NormalizedMessage {
    pub channel_id: String,
    pub password: String,
    pub op_id: String,
    pub fingerprint: String,
    pub fields: BTreeMap<String, String>,
    pub occurred_at: Option<i64>,
    pub ttl: Option<i64>,
}
impl AcceptRequest {
    pub(crate) fn normalize(self) -> Result<NormalizedMessage> {
        if self.message_id.is_some() {
            return Err(invalid("message_id is generated by the gateway"));
        }
        if self.thing_id.is_some() {
            return Err(invalid(
                "thing-scoped messages are outside ordinary C scope",
            ));
        }
        if self.channel_id.trim().is_empty() {
            return Err(invalid("channel_id required"));
        }
        if self.title.trim().is_empty() {
            return Err(invalid("title required"));
        }
        let password = password(&self.password)?.to_owned();
        let op_id = match self.op_id {
            Some(s) if !s.trim().is_empty() => op_id(&s)?,
            _ => format!(
                "{:013x}-{}",
                now().max(0),
                crate::types::generate_hex_id_128()
            ),
        };
        let mut fields = BTreeMap::new();
        fields.insert("title".into(), self.title.trim().to_owned());
        for (k, v) in [
            ("body", self.body),
            ("url", self.url),
            ("ciphertext", self.ciphertext),
        ] {
            if let Some(v) = optional(v) {
                fields.insert(k.into(), v);
            }
        }
        // Fingerprints use original severity; output follows NotificationSeverity.
        let severity = self.severity.as_deref().unwrap_or("").to_owned();
        let normalized = match severity.trim().to_ascii_lowercase().as_str() {
            "critical" => "critical",
            "high" => "high",
            "low" => "low",
            _ => "normal",
        };
        fields.insert("severity".into(), normalized.into());
        for (k, v) in [
            ("images", list(self.images, 2048)?),
            ("tags", list(self.tags, 64)?),
        ] {
            if !v.is_empty() {
                fields.insert(k.into(), serde_json::to_string(&v)?);
            }
        }
        let mut meta = Map::new();
        for (key, value) in self.metadata {
            let k = key.trim();
            let text = match &value {
                Value::String(s) => s.trim().to_owned(),
                Value::Number(_) | Value::Bool(_) => value.to_string(),
                _ => return Err(invalid("metadata value must be scalar")),
            };
            if k.is_empty()
                || k.len() > 64
                || text.is_empty()
                || text.len() > 512
                || meta.insert(k.into(), value).is_some()
            {
                return Err(invalid("metadata invalid"));
            }
        }
        if !meta.is_empty() {
            fields.insert("metadata".into(), serde_json::to_string(&meta)?);
        }
        let mut fingerprint_fields = fields.clone();
        fingerprint_fields.insert("title".into(), self.title.trim().into());
        fingerprint_fields.insert("severity".into(), severity);
        let fingerprint = blake3::hash(&serde_json::to_vec(&(
            channel_id(&self.channel_id)?,
            fingerprint_fields,
            self.occurred_at,
            self.ttl,
        ))?)
        .to_hex()
        .to_string();
        Ok(NormalizedMessage {
            channel_id: channel_id(&self.channel_id)?,
            password,
            op_id,
            fingerprint,
            fields,
            occurred_at: self.occurred_at,
            ttl: self.ttl,
        })
    }
}

pub(crate) fn generate_channel_id() -> String {
    let mut value = u128::from_be_bytes(rand::random());
    let mut out = [0_u8; 26];
    let alphabet = b"0123456789ABCDEFGHJKMNPQRSTVWXYZ";
    out[25] = alphabet[((value & 7) << 2) as usize];
    value >>= 3;
    for index in (0..25).rev() {
        out[index] = alphabet[(value & 31) as usize];
        value >>= 5;
    }
    String::from_utf8_lossy(&out).into_owned()
}

pub(crate) fn channel_id(raw: &str) -> Result<String> {
    let alphabet = b"0123456789ABCDEFGHJKMNPQRSTVWXYZ";
    let mut out = Vec::with_capacity(26);
    for byte in raw.bytes() {
        if byte.is_ascii_whitespace() || byte == b'-' {
            continue;
        }
        let b = match byte.to_ascii_uppercase() {
            b'O' => b'0',
            b'I' | b'L' => b'1',
            b => b,
        };
        if !alphabet.contains(&b) || out.len() == 26 {
            return Err(invalid("invalid channel id"));
        }
        out.push(b);
    }
    if out.len() != 26
        || alphabet
            .iter()
            .position(|b| *b == out[25])
            .is_none_or(|v| v & 3 != 0)
    {
        return Err(invalid("invalid channel id"));
    }
    Ok(String::from_utf8_lossy(&out).into_owned())
}
