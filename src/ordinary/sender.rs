//! Ordinary sender input delegates pure preparation to the product message domain.
use super::store::{KernelError, Result, now};
use crate::domain_model::message::{MessageInput, MessageSend};
use serde::{Deserialize, Deserializer};
use serde_json::{Map, Value};
use std::collections::BTreeMap;

pub const MAX_TTL_MS: i64 = crate::delivery_core::payload::MAX_PROVIDER_TTL_MILLIS;
#[derive(Debug, Deserialize, Clone, Default)]
pub struct AcceptRequest {
    pub channel_id: String,
    pub password: String,
    /// Present only after the normal product channel authorization path.
    #[serde(skip)]
    pub(crate) authorized_channel: Option<[u8; 16]>,
    #[serde(skip)]
    pub(crate) submit_clock: Option<i64>,
    pub title: String,
    #[serde(default)]
    pub body: Option<String>,
    #[serde(default, deserialize_with = "empty_none")]
    pub op_id: Option<String>,
    #[serde(default, deserialize_with = "timestamp")]
    pub ttl: Option<i64>,
    #[serde(default, deserialize_with = "timestamp")]
    pub occurred_at: Option<i64>,
    #[serde(default)]
    pub severity: Option<String>,
    #[serde(default)]
    pub url: Option<String>,
    #[serde(default)]
    pub images: Vec<String>,
    #[serde(default)]
    pub ciphertext: Option<String>,
    #[serde(default)]
    pub tags: Vec<String>,
    #[serde(default, deserialize_with = "metadata")]
    pub metadata: Map<String, Value>,
    #[serde(default)]
    pub thing_id: Option<String>,
    #[serde(default, rename = "message_id", deserialize_with = "forbidden")]
    pub(crate) message_id: Option<Value>,
}
fn invalid(message: &str) -> KernelError {
    KernelError::Invalid(message.into())
}
fn forbidden<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Option<Value>, D::Error> {
    let _ = serde::de::IgnoredAny::deserialize(d)?;
    Err(serde::de::Error::custom(
        "message_id is generated by the gateway",
    ))
}
fn empty_none<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Option<String>, D::Error> {
    Ok(Option::<String>::deserialize(d)?.and_then(|v| optional(Some(v))))
}
fn timestamp<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Option<i64>, D::Error> {
    let v = Option::<Value>::deserialize(d)?;
    let n = match v {
        None | Some(Value::Null) => return Ok(None),
        Some(Value::String(s)) if s.trim().is_empty() => return Ok(None),
        Some(Value::String(s)) => s.trim().parse::<i64>().map_err(serde::de::Error::custom)?,
        Some(Value::Number(n)) => n
            .as_i64()
            .ok_or_else(|| serde::de::Error::custom("timestamp must be integer"))?,
        _ => return Err(serde::de::Error::custom("timestamp must be integer")),
    };
    Ok(Some(if n.unsigned_abs() < 1_000_000_000_000 {
        n.saturating_mul(1000)
    } else {
        n
    }))
}
fn metadata<'de, D: Deserializer<'de>>(d: D) -> std::result::Result<Map<String, Value>, D::Error> {
    let v = Option::<Map<String, Value>>::deserialize(d)?.unwrap_or_default();
    let mut out = Map::new();
    for (k, v) in v {
        let k = k.trim();
        if k.is_empty() || out.insert(k.to_owned(), v).is_some() {
            return Err(serde::de::Error::custom("metadata key invalid"));
        }
    }
    Ok(out)
}
fn optional(v: Option<String>) -> Option<String> {
    v.and_then(|s| {
        let s = s.trim();
        (!s.is_empty()).then(|| s.to_owned())
    })
}
pub(crate) fn op_id(raw: &str) -> Result<String> {
    let s = raw.trim();
    if s.is_empty()
        || s.len() > 128
        || !s
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | ':' | '-'))
    {
        return Err(invalid("op_id invalid"));
    }
    Ok(s.into())
}
pub(crate) fn password(raw: &str) -> Result<&str> {
    let s = raw.trim();
    if !(8..=128).contains(&s.len()) {
        return Err(invalid("channel password length must be between 8 and 128"));
    }
    Ok(s)
}
pub(crate) struct NormalizedMessage {
    pub channel_id: String,
    pub thing_id: Option<String>,
    pub password: String,
    pub op_id: String,
    pub fingerprint: String,
    pub fields: BTreeMap<String, String>,
    pub occurred_at: Option<i64>,
    pub ttl: Option<i64>,
}
impl AcceptRequest {
    pub(crate) fn normalize(self) -> Result<NormalizedMessage> {
        if self.message_id.is_some() {
            return Err(invalid("message_id is generated by the gateway"));
        }
        let channel_id = channel_id(&self.channel_id)?;
        if self.authorized_channel.is_some_and(|authorized| {
            crate::value::ChannelId::from(authorized).to_string() != channel_id
        }) {
            return Err(KernelError::Unauthorized);
        }
        let password = if self.authorized_channel.is_some() {
            String::new()
        } else {
            password(&self.password)?.to_owned()
        };
        let prepared = MessageSend::new(MessageInput {
            op_id: self.op_id,
            thing_id: self.thing_id,
            occurred_at: self.occurred_at,
            title: self.title,
            body: self.body,
            severity: self.severity,
            ttl: self.ttl,
            url: self.url,
            images: self.images,
            ciphertext: self.ciphertext,
            tags: self.tags,
            metadata: self.metadata,
        })
        .prepare(self.submit_clock.unwrap_or_else(now))
        .map_err(|error| match error {
            crate::delivery_core::error::CoreError::Validation { message, code } => {
                KernelError::Control {
                    status: 400,
                    code,
                    message,
                }
            }
            other => invalid(&other.to_string()),
        })?;
        Ok(NormalizedMessage {
            channel_id,
            thing_id: prepared.thing_id,
            password,
            op_id: prepared.op_id,
            fingerprint: prepared.fingerprint,
            fields: prepared.fields,
            occurred_at: Some(prepared.occurred_at),
            ttl: prepared.ttl,
        })
    }
}

pub(crate) fn channel_id(raw: &str) -> Result<String> {
    let alphabet = b"0123456789ABCDEFGHJKMNPQRSTVWXYZ";
    let mut out = Vec::with_capacity(26);
    for byte in raw.bytes() {
        if byte.is_ascii_whitespace() || byte == b'-' {
            continue;
        }
        let b = match byte.to_ascii_uppercase() {
            b'O' => b'0',
            b'I' | b'L' => b'1',
            b => b,
        };
        if !alphabet.contains(&b) || out.len() == 26 {
            return Err(invalid("invalid channel id"));
        }
        out.push(b);
    }
    if out.len() != 26
        || alphabet
            .iter()
            .position(|b| *b == out[25])
            .is_none_or(|v| v & 3 != 0)
    {
        return Err(invalid("invalid channel id"));
    }
    Ok(String::from_utf8_lossy(&out).into_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn request() -> AcceptRequest {
        AcceptRequest {
            channel_id: crate::value::ChannelId::from([7; 16]).to_string(),
            authorized_channel: Some([7; 16]),
            submit_clock: Some(123),
            op_id: Some("product-ordinary-op".into()),
            title: "message".into(),
            ..AcceptRequest::default()
        }
    }

    #[test]
    fn authorized_product_acceptance_keeps_thing_association_and_content() {
        let mut input = request();
        input.thing_id = Some("thing-associated".into());
        input.occurred_at = Some(456);
        input.body = Some("  正文 \"完整\"  ".into());
        input.url = Some(" https://synthetic.invalid/path ".into());
        input.tags = vec![" one ".into(), "one".into()];
        input
            .metadata
            .insert("amount".into(), serde_json::json!(-12.5));
        let output = input.normalize().unwrap();
        assert_eq!(
            output.channel_id,
            crate::value::ChannelId::from([7; 16]).to_string()
        );
        assert!(output.password.is_empty());
        assert_eq!(output.occurred_at, Some(456));
        assert_eq!(
            output.fields.get("thing_id").map(String::as_str),
            Some("thing-associated")
        );
        assert_eq!(
            output.fields.get("body").map(String::as_str),
            Some("正文 \"完整\"")
        );
        assert_eq!(
            output.fields.get("tags").map(String::as_str),
            Some("[\"one\"]")
        );
        assert_eq!(
            serde_json::from_str::<Value>(&output.fields["metadata"]).unwrap()["amount"],
            serde_json::json!(-12.5)
        );
        assert!(!output.fields.contains_key("message_id"));
        assert!(!output.fields.contains_key("delivery_id"));
    }

    #[test]
    fn wire_input_cannot_claim_the_internal_authorized_context() {
        let input: AcceptRequest = serde_json::from_value(serde_json::json!({
            "channel_id": crate::value::ChannelId::from([7;16]).to_string(),
            "password": String::new(),
            "title": "message",
            "authorized_channel": [7,7,7,7,7,7,7,7,7,7,7,7,7,7,7,7],
            "submit_clock": 123
        }))
        .unwrap();
        assert!(input.authorized_channel.is_none());
        assert!(input.submit_clock.is_none());
    }

    #[test]
    fn internal_authorization_cannot_be_reused_for_another_channel() {
        let mut input = request();
        input.authorized_channel = Some([8; 16]);
        assert!(matches!(input.normalize(), Err(KernelError::Unauthorized)));
    }
}
